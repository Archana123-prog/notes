const jwt = require('jsonwebtoken');

/**
 * Middleware to require JWT Authentication.
 * Expected header: Authorization: Bearer <token>
 */
const requireAuth = (req, res, next) => {
  const authHeader = req.headers.authorization;

  if (!authHeader || !authHeader.startsWith('Bearer ')) {
    return res.status(401).json({
      success: false,
      message: 'Access denied. No authentication token provided in Authorization header.',
    });
  }

  const token = authHeader.split(' ')[1];

  try {
    const decoded = jwt.verify(token, process.env.JWT_SECRET || 'super_secret_jwt_key_notes_app_2026');
    req.user = decoded; // { id, email, name, iat, exp }
    next();
  } catch (error) {
    if (error.name === 'TokenExpiredError') {
      return res.status(401).json({
        success: false,
        message: 'Authentication token has expired. Please log in again.',
      });
    }
    return res.status(401).json({
      success: false,
      message: 'Invalid authentication token.',
    });
  }
};

/**
 * Optional Authentication Middleware.
 * If token is provided and valid, attaches req.user.
 * If not provided or invalid, proceeds with req.user = null.
 */
const optionalAuth = (req, res, next) => {
  const authHeader = req.headers.authorization;

  if (!authHeader || !authHeader.startsWith('Bearer ')) {
    req.user = null;
    return next();
  }

  const token = authHeader.split(' ')[1];

  try {
    const decoded = jwt.verify(token, process.env.JWT_SECRET || 'super_secret_jwt_key_notes_app_2026');
    req.user = decoded;
  } catch (err) {
    req.user = null;
  }
  next();
};

module.exports = {
  requireAuth,
  optionalAuth,
};
